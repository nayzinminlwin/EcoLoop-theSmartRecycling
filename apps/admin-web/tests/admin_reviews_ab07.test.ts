describe("Phase AB-07 — Mock Verification Repository Resolution & Invariants", () => {
  it("provides detailed multi-object review and server-computed preview in mock mode", async () => {
    const mockBundle = createMockRepositories();
    mockBundle.controls.setAuthState({ uid: "ADM-001", role: "admin", isSignedIn: true });

    // 1. Get review detail
    const detail = await mockBundle.repositories.verification.getReviewDetail!("REV-1087");
    assert.ok(detail);
    assert.equal(detail.review.ticketId, "REV-1087");
    assert.ok(detail.findings.length > 0);

    // 2. Preview resolution with affirmative empty chamber
    const emptyPreview = await mockBundle.repositories.verification.previewResolution!({
      ticketId: "REV-1087",
      inventoryState: "empty",
      objects: [],
    });
    assert.equal(emptyPreview.outcome, "empty");
    assert.equal(emptyPreview.pointsAwarded, 0);
    assert.equal(emptyPreview.spaceContributionSpc, 0);
    assert.equal(emptyPreview.spaceDeltaSpc, -10);

    // 3. Preview resolution with 2 accepted items
    const objects: ObjectResolutionDecisionInput[] = [
      { objectId: "obj-1", resolvedClass: "plastic_bottle", decision: "accept" },
      { objectId: "obj-2", resolvedClass: "aluminium_can", decision: "accept" },
    ];
    const acceptPreview = await mockBundle.repositories.verification.previewResolution!({
      ticketId: "REV-1087",
      inventoryState: "resolved",
      objects,
    });
    assert.equal(acceptPreview.outcome, "verified");
    assert.equal(acceptPreview.acceptedCount, 2);
    assert.equal(acceptPreview.pointsAwarded, 20);
    assert.equal(acceptPreview.spaceContributionSpc, 20);
  });

  it("resolves review and awards points idempotently in mock mode", async () => {
    const mockBundle = createMockRepositories();
    mockBundle.controls.setAuthState({ uid: "ADM-001", role: "admin", isSignedIn: true });

    const input = {
      ticketId: "REV-1087",
      expectedDecisionVersion: 1,
      inventoryState: "resolved" as const,
      objects: [
        { objectId: "obj-1", resolvedClass: "plastic_bottle", decision: "accept" as const, note: "Verified bottle" },
      ],
      explanation: "Verified by operator review",
    };

    const receipt = await mockBundle.repositories.verification.resolveReview!(input);
    assert.equal(receipt.detail.ticket.status, "approved");
    assert.ok(receipt.wallet.balance > 0);
  });
});

